#!/usr/bin/env python3
"""Make responsive copies of the photos in img/.

For every img/<name>.jpg (except og-image and copies this script made) it
writes img/<name>-<width>.jpg and .webp at widths 480, 800 and 1200, capped
at the photo's own width, and js/images.js listing what exists so the page
can build srcset attributes. Stale copies of removed photos are deleted.

Run it after adding or replacing a photo (needs Pillow: pip install Pillow):

    python3 tools/images.py
"""
import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
IMG = ROOT / 'img'
WIDTHS = (480, 800, 1200)
SKIP = {'og-image'}
COPY = re.compile(r'^(.+)-(\d+)$')

manifest = {}
for src in sorted(IMG.glob('*.jpg')):
    name = src.stem
    if name in SKIP or COPY.match(name):
        continue
    im = ImageOps.exif_transpose(Image.open(src)).convert('RGB')
    w, h = im.size
    widths = sorted({min(x, w) for x in WIDTHS})
    for tw in widths:
        out = im if tw == w else im.resize((tw, round(h * tw / w)), Image.LANCZOS)
        out.save(IMG / f'{name}-{tw}.jpg', 'JPEG', quality=80, optimize=True, progressive=True)
        out.save(IMG / f'{name}-{tw}.webp', 'WEBP', quality=78, method=6)
    manifest[name] = {'w': w, 'h': h, 'widths': widths}
    print(f'{name}: {w}x{h} -> {widths}')

for copy in list(IMG.glob('*-*.jpg')) + list(IMG.glob('*-*.webp')):
    m = COPY.match(copy.stem)
    if m and (m.group(1) not in manifest or int(m.group(2)) not in manifest[m.group(1)]['widths']):
        copy.unlink()
        print(f'removed stale {copy.name}')

(ROOT / 'js' / 'images.js').write_text(
    '// Generated by tools/images.py - do not edit by hand.\n'
    '// Sizes available in img/ for each photo, used to build srcset attributes.\n'
    'export const IMAGES = ' + json.dumps(manifest, indent=2) + ';\n')
